-- Esquema de la API de gestión de pedidos

CREATE TABLE usuarios (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,          -- Hash BCrypt, nunca la contraseña en claro
    nombre        VARCHAR(100) NOT NULL,
    email         VARCHAR(150) NOT NULL,
    rol           VARCHAR(10)  NOT NULL CHECK (rol IN ('USER', 'ADMIN'))
);

CREATE TABLE productos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100)   NOT NULL,
    descripcion VARCHAR(500),
    precio      NUMERIC(10, 2) NOT NULL CHECK (precio >= 0),
    stock       INTEGER        NOT NULL CHECK (stock >= 0),
    version     BIGINT         NOT NULL DEFAULT 0   -- Bloqueo optimista (@Version en Producto)
);

CREATE TABLE pedidos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT         NOT NULL REFERENCES usuarios (id),   -- Propietario del pedido
    fecha      TIMESTAMPTZ    NOT NULL,
    estado     VARCHAR(10)    NOT NULL CHECK (estado IN ('PENDIENTE', 'ENVIADO', 'CANCELADO')),
    total      NUMERIC(10, 2) NOT NULL CHECK (total >= 0)
);

CREATE INDEX idx_pedidos_usuario ON pedidos (usuario_id);

CREATE TABLE lineas_pedido (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT         NOT NULL REFERENCES pedidos (id) ON DELETE CASCADE,
    producto_id     BIGINT         NOT NULL REFERENCES productos (id),
    cantidad        INTEGER        NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(10, 2) NOT NULL CHECK (precio_unitario >= 0)  -- Precio en el momento de la compra
);

CREATE INDEX idx_lineas_pedido_pedido ON lineas_pedido (pedido_id);
